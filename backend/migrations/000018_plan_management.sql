BEGIN;

CREATE TABLE plans (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id uuid NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_id uuid NOT NULL,
    title varchar(120) NOT NULL,
    description text NOT NULL DEFAULT '',
    starts_at timestamptz NOT NULL,
    cover_emoji varchar(32) NOT NULL DEFAULT '',
    cover_image_key text NOT NULL DEFAULT '',
    plan_status varchar(16) NOT NULL DEFAULT 'active',
    completed_at timestamptz,
    deleted_at timestamptz,
    CONSTRAINT ck_plans_status CHECK (plan_status IN ('active', 'completed', 'deleted')),
    CONSTRAINT ck_plans_single_cover CHECK ((cover_emoji <> '') <> (cover_image_key <> ''))
);
CREATE UNIQUE INDEX ux_plans_business_id ON plans (business_id);
CREATE INDEX ix_plans_user_status_start ON plans (user_id, plan_status, starts_at) WHERE deleted_at IS NULL;

CREATE TABLE plan_reminders (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id uuid NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_id uuid NOT NULL,
    plan_business_id uuid NOT NULL,
    lead_minutes integer NOT NULL,
    remind_at timestamptz NOT NULL,
    reminder_status varchar(16) NOT NULL DEFAULT 'pending',
    is_configured boolean NOT NULL DEFAULT true,
    sent_at timestamptz,
    CONSTRAINT ck_plan_reminders_lead_minutes CHECK (lead_minutes BETWEEN 1 AND 525600),
    CONSTRAINT ck_plan_reminders_status CHECK (reminder_status IN ('pending', 'sent', 'cancelled'))
);
CREATE UNIQUE INDEX ux_plan_reminders_business_id ON plan_reminders (business_id);
CREATE INDEX ix_plan_reminders_user_plan ON plan_reminders (user_id, plan_business_id);
CREATE INDEX ix_plan_reminders_ready ON plan_reminders (remind_at, created_at) WHERE reminder_status = 'pending';
CREATE INDEX ix_plan_reminders_configured ON plan_reminders (plan_business_id, lead_minutes) WHERE is_configured = true;

