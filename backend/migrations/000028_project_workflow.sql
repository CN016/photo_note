-- 在迁移事务中一次性回填历史状态。仅遍历 content 树，避免把节点属性内的普通文本当作动作。
WITH whitespace(value) AS (VALUES (U&'\0009\000A\000B\000C\000D\0020\0085\00A0\1680\2000\2001\2002\2003\2004\2005\2006\2007\2008\2009\200A\2028\2029\202F\205F\3000'))
UPDATE projects p SET status = CASE
    WHEN EXISTS (
        WITH RECURSIVE nodes(node, in_task) AS (
            SELECT p.document, false
            UNION ALL
            SELECT child, nodes.in_task OR nodes.node->>'type' = 'taskItem'
            FROM nodes CROSS JOIN LATERAL jsonb_array_elements(
                CASE WHEN jsonb_typeof(nodes.node->'content') = 'array' THEN nodes.node->'content' ELSE '[]'::jsonb END
            ) child
        )
        SELECT 1 FROM nodes WHERE
            (node->>'type' = 'taskItem' AND node->'attrs'->'checked' = 'true'::jsonb)
            OR (in_task AND node->>'type' = 'text' AND btrim(COALESCE(node->>'text',''), (SELECT value FROM whitespace)) <> ''
                AND jsonb_typeof(node->'marks') = 'array' AND node->'marks' @> '[{"type":"strike"}]'::jsonb)
    ) THEN CASE WHEN btrim(p.manual_summary, (SELECT value FROM whitespace)) = '' THEN 'executed' ELSE 'completed' END
    ELSE 'unfinished' END;

