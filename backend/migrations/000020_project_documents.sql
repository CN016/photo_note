BEGIN;

CREATE TABLE projects (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id uuid NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_id uuid NOT NULL,
    title varchar(120) NOT NULL,
    cover_emoji varchar(32) NOT NULL DEFAULT '',
    cover_image_key text NOT NULL DEFAULT '',
    cover_file_name text NOT NULL DEFAULT '',
    document_schema_version smallint NOT NULL DEFAULT 1,
    document jsonb NOT NULL DEFAULT '{"type":"doc","content":[{"type":"paragraph"}]}'::jsonb,
    search_text text NOT NULL DEFAULT '',
    search_grams text[] NOT NULL DEFAULT ARRAY[]::text[],
    revision bigint NOT NULL DEFAULT 1,
    deleted_at timestamptz,
    CONSTRAINT ck_projects_title_not_empty CHECK (length(btrim(title)) > 0),
    CONSTRAINT ck_projects_single_cover CHECK ((cover_emoji <> '') <> (cover_image_key <> '')),
    CONSTRAINT ck_projects_document_schema_version CHECK (document_schema_version = 1),
    CONSTRAINT ck_projects_revision_positive CHECK (revision > 0)
);
CREATE UNIQUE INDEX ux_projects_business_id ON projects (business_id);
CREATE INDEX ix_projects_user_updated ON projects (user_id, updated_at DESC) WHERE deleted_at IS NULL;
CREATE INDEX ix_projects_search_grams ON projects USING gin (search_grams);

CREATE TABLE project_inspiration_usages (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id uuid NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_id uuid NOT NULL,
    project_business_id uuid NOT NULL,
    inspiration_business_id uuid NOT NULL
);
CREATE UNIQUE INDEX ux_project_inspiration_usages_business_id ON project_inspiration_usages (business_id);
CREATE UNIQUE INDEX ux_project_inspiration_usages_pair ON project_inspiration_usages (user_id, project_business_id, inspiration_business_id);
CREATE INDEX ix_project_inspiration_usages_inspiration ON project_inspiration_usages (user_id, inspiration_business_id);

CREATE TABLE project_attachments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id uuid NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_id uuid NOT NULL,
    project_business_id uuid NOT NULL,
    storekey text NOT NULL,
    file_name text NOT NULL,
    file_size bigint NOT NULL,
    content_type varchar(160) NOT NULL,
    asset_role varchar(16) NOT NULL,
    CONSTRAINT ck_project_attachments_file_size CHECK (file_size > 0),
    CONSTRAINT ck_project_attachments_role CHECK (asset_role IN ('cover', 'content', 'both'))
);
CREATE UNIQUE INDEX ux_project_attachments_business_id ON project_attachments (business_id);
CREATE UNIQUE INDEX ux_project_attachments_project_storekey ON project_attachments (user_id, project_business_id, storekey);
CREATE INDEX ix_project_attachments_user_project ON project_attachments (user_id, project_business_id);

UPDATE app_configs
SET is_public = true, updated_at = CURRENT_TIMESTAMP
WHERE config_key = 'files.max_upload_bytes' AND is_secret = false;

COMMENT ON TABLE projects IS '用户私有的项目文档，正文以带版本号的 JSONB 保存，删除采用软删除。';
COMMENT ON COLUMN projects.id IS '数据库内部自增主键，仅供数据库内部使用，不返回客户端且不用于表间关联。';
COMMENT ON COLUMN projects.business_id IS '项目对外业务 UUID，每条项目唯一，由服务端生成。';
COMMENT ON COLUMN projects.created_at IS '项目创建时间，使用带时区时间并统一以 UTC 保存。';
COMMENT ON COLUMN projects.updated_at IS '项目或正文最后修改时间，使用带时区时间并统一以 UTC 保存。';
COMMENT ON COLUMN projects.user_id IS '项目所属用户的 users.business_id，由访问令牌确定，不设置数据库外键。';
COMMENT ON COLUMN projects.title IS '项目标题，去除首尾空白后不能为空且最多 120 个 Unicode 字符。';
COMMENT ON COLUMN projects.cover_emoji IS '封面 emoji；封面为图片时为空，且与 cover_image_key 只能设置其中一个。';
COMMENT ON COLUMN projects.cover_image_key IS '封面图片的私有文件 storekey；封面为 emoji 时为空，不是通用文件存储定位表。';
COMMENT ON COLUMN projects.cover_file_name IS '封面图片的原始文件名，仅供界面展示，不用于生成文件系统路径。';
COMMENT ON COLUMN projects.document_schema_version IS '正文 JSONB 的格式版本；版本 1 使用受控的 ProseMirror 文档结构。';
COMMENT ON COLUMN projects.document IS '项目正文 JSONB，保存文本、格式标记、灵感图协议引用及附件块布局。';
COMMENT ON COLUMN projects.search_text IS '由标题和正文文字提取并规范化的检索文本，不包含二进制附件内容。';
COMMENT ON COLUMN projects.search_grams IS '检索文本中去重的一元和二元 Unicode 字符 n-gram，用于 GIN 候选检索。';
COMMENT ON COLUMN projects.revision IS '项目递增修订号；更新时用于检测并发编辑，避免覆盖较新的正文。';
COMMENT ON COLUMN projects.deleted_at IS '项目软删除时间；为空表示项目仍在列表中，关联资源在回收站期间保留。';

COMMENT ON TABLE project_inspiration_usages IS '项目引用灵感图关系表，用于检索项目使用情况并阻止删除仍被引用的灵感图。';
COMMENT ON COLUMN project_inspiration_usages.id IS '数据库内部自增主键，仅供数据库内部使用，不返回客户端且不用于表间关联。';
COMMENT ON COLUMN project_inspiration_usages.business_id IS '项目灵感图关系对外业务 UUID，每条关系唯一，由服务端生成。';
COMMENT ON COLUMN project_inspiration_usages.created_at IS '关系创建时间，使用带时区时间并统一以 UTC 保存。';
COMMENT ON COLUMN project_inspiration_usages.updated_at IS '关系最后修改时间，使用带时区时间并统一以 UTC 保存。';
COMMENT ON COLUMN project_inspiration_usages.user_id IS '项目和灵感图所属用户的 users.business_id，由访问令牌确定，不设置数据库外键。';
COMMENT ON COLUMN project_inspiration_usages.project_business_id IS '引用灵感图的项目 business_id，不使用自增 ID 且不设置数据库外键。';
COMMENT ON COLUMN project_inspiration_usages.inspiration_business_id IS '被项目引用的灵感图 business_id，不使用自增 ID 且不设置数据库外键。';

COMMENT ON TABLE project_attachments IS '项目已引用的非灵感图文件清单，包含封面和正文附件，不管理底层文件生命周期。';
COMMENT ON COLUMN project_attachments.id IS '数据库内部自增主键，仅供数据库内部使用，不返回客户端且不用于表间关联。';
COMMENT ON COLUMN project_attachments.business_id IS '项目附件记录对外业务 UUID，每条记录唯一，由服务端生成。';
COMMENT ON COLUMN project_attachments.created_at IS '附件登记时间，使用带时区时间并统一以 UTC 保存。';
COMMENT ON COLUMN project_attachments.updated_at IS '附件元数据最后修改时间，使用带时区时间并统一以 UTC 保存。';
COMMENT ON COLUMN project_attachments.user_id IS '关联项目所属用户的 users.business_id，由访问令牌确定，不代表通用文件归属。';
COMMENT ON COLUMN project_attachments.project_business_id IS '使用该资源的项目 business_id，不使用自增 ID 且不设置数据库外键。';
COMMENT ON COLUMN project_attachments.storekey IS '私有文件存储键，通过现有文件存储服务读取，数据库不保存文件字节。';
COMMENT ON COLUMN project_attachments.file_name IS '上传时的文件名，经清理后仅供项目附件展示，不用于文件路径。';
COMMENT ON COLUMN project_attachments.file_size IS 'storekey 指向文件的实际字节数，由服务端读取文件存储后确定。';
COMMENT ON COLUMN project_attachments.content_type IS '服务端识别的文件媒体类型，用于安全的预览分派。';
COMMENT ON COLUMN project_attachments.asset_role IS '项目资源用途；同一 storekey 同时被封面和正文引用时记录 both。';

COMMIT;
