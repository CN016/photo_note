BEGIN;

CREATE TABLE portfolios (

  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id uuid NOT NULL UNIQUE,
  orgid bigint NOT NULL CHECK (orgid = -1 OR orgid BETWEEN 1 AND 9007199254740991),
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  user_id uuid NOT NULL,
  title varchar(120) NOT NULL,
  description text NOT NULL DEFAULT '',
  tag_ids uuid[] NOT NULL DEFAULT ARRAY[]::uuid[],
  share_token_hash varchar(64)

);

COMMENT ON TABLE portfolios IS '独立作品集及公开分享状态。';

COMMENT ON COLUMN portfolios.id IS '数据库内部自增主键，不作为接口标识。';

COMMENT ON COLUMN portfolios.business_id IS '业务 UUID，全局唯一。';

COMMENT ON COLUMN portfolios.orgid IS '空间业务编号，-1 为个人空间，正数为组织。';

COMMENT ON COLUMN portfolios.created_at IS '创建时间，带时区。';

COMMENT ON COLUMN portfolios.updated_at IS '最近更新时间，带时区。';

COMMENT ON COLUMN portfolios.user_id IS '创建者用户业务 UUID，由服务端会话确定。';

COMMENT ON COLUMN portfolios.title IS '作品集标题。';

COMMENT ON COLUMN portfolios.description IS '作品集说明。';

COMMENT ON COLUMN portfolios.tag_ids IS '当前用户的标签业务 UUID 数组。';

COMMENT ON COLUMN portfolios.share_token_hash IS '公开分享令牌摘要，空值表示未启用。';

CREATE INDEX ix_portfolios_scope ON portfolios (orgid, user_id);

CREATE TABLE portfolio_photos (

  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id uuid NOT NULL UNIQUE,
  orgid bigint NOT NULL CHECK (orgid = -1 OR orgid BETWEEN 1 AND 9007199254740991),
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  user_id uuid NOT NULL,
  portfolio_id uuid NOT NULL,
  image_key text NOT NULL,
  title varchar(255) NOT NULL DEFAULT '',
  tag_ids uuid[] NOT NULL DEFAULT ARRAY[]::uuid[],
  sort_order bigint NOT NULL DEFAULT 0,
  image_metadata jsonb NOT NULL DEFAULT '{}'::jsonb

);

COMMENT ON TABLE portfolio_photos IS '作品集照片，文件为公开副本。';

COMMENT ON COLUMN portfolio_photos.id IS '数据库内部自增主键，不作为接口标识。';

COMMENT ON COLUMN portfolio_photos.business_id IS '业务 UUID，全局唯一。';

COMMENT ON COLUMN portfolio_photos.orgid IS '空间业务编号，-1 为个人空间，正数为组织。';

COMMENT ON COLUMN portfolio_photos.created_at IS '创建时间，带时区。';

COMMENT ON COLUMN portfolio_photos.updated_at IS '最近更新时间，带时区。';

COMMENT ON COLUMN portfolio_photos.user_id IS '创建者用户业务 UUID，由服务端会话确定。';

COMMENT ON COLUMN portfolio_photos.portfolio_id IS '所属作品集业务 UUID。';

COMMENT ON COLUMN portfolio_photos.image_key IS '公开图片的服务端生成存储 key。';

COMMENT ON COLUMN portfolio_photos.title IS '照片展示标题。';

COMMENT ON COLUMN portfolio_photos.tag_ids IS '当前用户的照片标签业务 UUID 数组。';

COMMENT ON COLUMN portfolio_photos.sort_order IS '作品集内展示顺序。';

COMMENT ON COLUMN portfolio_photos.image_metadata IS '图片拍摄属性快照，原文件可包含其他元数据。';

CREATE INDEX ix_portfolio_photos_scope ON portfolio_photos (orgid, user_id);

CREATE TABLE portfolio_projects (

  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id uuid NOT NULL UNIQUE,
  orgid bigint NOT NULL CHECK (orgid = -1 OR orgid BETWEEN 1 AND 9007199254740991),
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  user_id uuid NOT NULL,
  portfolio_id uuid NOT NULL,
  project_id uuid NOT NULL

);

COMMENT ON TABLE portfolio_projects IS '作品集关联拍摄策划，不建立数据库外键。';

COMMENT ON COLUMN portfolio_projects.id IS '数据库内部自增主键，不作为接口标识。';

COMMENT ON COLUMN portfolio_projects.business_id IS '业务 UUID，全局唯一。';

COMMENT ON COLUMN portfolio_projects.orgid IS '空间业务编号，-1 为个人空间，正数为组织。';

COMMENT ON COLUMN portfolio_projects.created_at IS '创建时间，带时区。';

COMMENT ON COLUMN portfolio_projects.updated_at IS '最近更新时间，带时区。';

COMMENT ON COLUMN portfolio_projects.user_id IS '创建者用户业务 UUID，由服务端会话确定。';

COMMENT ON COLUMN portfolio_projects.portfolio_id IS '所属作品集业务 UUID。';

COMMENT ON COLUMN portfolio_projects.project_id IS '关联拍摄策划业务 UUID。';

CREATE INDEX ix_portfolio_projects_scope ON portfolio_projects (orgid, user_id);

CREATE UNIQUE INDEX ix_portfolios_share_hash ON portfolios (share_token_hash) WHERE share_token_hash IS NOT NULL;

CREATE INDEX ix_portfolios_tags ON portfolios USING gin (tag_ids);

CREATE INDEX ix_portfolio_photos_tags ON portfolio_photos USING gin (tag_ids);

CREATE INDEX ix_portfolio_photos_order ON portfolio_photos (orgid, user_id, portfolio_id, sort_order);

CREATE UNIQUE INDEX ix_portfolio_projects_unique ON portfolio_projects (orgid, user_id, portfolio_id, project_id);

COMMIT;
