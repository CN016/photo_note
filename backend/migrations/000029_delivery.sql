  internal_note text NOT NULL DEFAULT '',
  stage text NOT NULL CHECK (stage IN ('upload','cull','select','retouch','delivered')),
  status text NOT NULL CHECK (status IN ('active','paused','completed','archived','cancelled')),
  version integer NOT NULL CHECK (version > 0),
  limit_mode text NOT NULL CHECK (limit_mode IN ('unlimited','max','exact')),
  selection_limit integer NOT NULL CHECK (selection_limit BETWEEN 0 AND 10000),
  deadline timestamptz,
  expires_at timestamptz,
  allow_original boolean NOT NULL DEFAULT false,
  allow_download boolean NOT NULL DEFAULT true,
  share_hash varchar(64),
  access_hash text NOT NULL DEFAULT '',
