BEGIN;

CREATE TABLE app_configs (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    business_id uuid NOT NULL,
    config_key text NOT NULL,
    config_value text NOT NULL,
    description text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX ux_app_configs_business_id
    ON app_configs (business_id);
CREATE UNIQUE INDEX ux_app_configs_config_key
    ON app_configs (config_key);

CREATE TABLE users (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    business_id uuid NOT NULL,
    nickname varchar(64) NOT NULL,
    phone varchar(16) NOT NULL,
    password_hash text NOT NULL,
    avatar_key text,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_users_phone_e164
        CHECK (phone ~ '^\+[1-9][0-9]{1,14}$')
);

CREATE UNIQUE INDEX ux_users_business_id
    ON users (business_id);
CREATE UNIQUE INDEX ux_users_phone
    ON users (phone);

CREATE TABLE tags (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    business_id uuid NOT NULL,
    user_id uuid NOT NULL,
    content varchar(64) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX ux_tags_business_id
    ON tags (business_id);
CREATE INDEX ix_tags_user_id
    ON tags (user_id);

CREATE TABLE inspirations (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    business_id uuid NOT NULL,
    user_id uuid NOT NULL,
    tag_ids uuid[] NOT NULL DEFAULT ARRAY[]::uuid[],
    image_key text NOT NULL,
    data jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX ux_inspirations_business_id
    ON inspirations (business_id);
CREATE INDEX ix_inspirations_user_id
    ON inspirations (user_id);
CREATE INDEX ix_inspirations_tag_ids_gin
    ON inspirations USING GIN (tag_ids);

COMMENT ON COLUMN app_configs.business_id IS
    'Public business UUID; generated by the application.';
COMMENT ON COLUMN users.business_id IS
    'Public business UUID; generated by the application.';
COMMENT ON COLUMN tags.business_id IS
    'Public business UUID; generated by the application.';
COMMENT ON COLUMN tags.user_id IS
    'Stores users.business_id; intentionally has no foreign key constraint.';
COMMENT ON COLUMN inspirations.business_id IS
    'Public business UUID; generated by the application.';
COMMENT ON COLUMN inspirations.user_id IS
    'Stores users.business_id; intentionally has no foreign key constraint.';
COMMENT ON COLUMN inspirations.tag_ids IS
    'Array of tags.business_id values; ownership and existence are checked by the service.';
COMMENT ON COLUMN inspirations.data IS
    'Versioned editor data as a JSON object.';

COMMIT;
