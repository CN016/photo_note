CREATE TABLE notifications (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id uuid NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    user_id uuid NOT NULL,
    event_type varchar(64) NOT NULL,
    event_key varchar(180) NOT NULL,
    resource_type varchar(32) NOT NULL DEFAULT '',
    resource_business_id uuid,
    payload jsonb NOT NULL DEFAULT '{}'::jsonb,
    read_at timestamptz
);
CREATE UNIQUE INDEX ux_notifications_business_id ON notifications (business_id);
CREATE UNIQUE INDEX ux_notifications_user_event_key ON notifications (user_id, event_key);
CREATE INDEX ix_notifications_user_created ON notifications (user_id, created_at DESC);
CREATE INDEX ix_notifications_user_unread ON notifications (user_id, read_at, created_at DESC);

CREATE TABLE notice_config (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id uuid NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    user_id uuid NOT NULL,
    provider varchar(16) NOT NULL,
    config_name varchar(80) NOT NULL,
    webhook_url text NOT NULL,
    signing_secret text NOT NULL DEFAULT '',
    enabled boolean NOT NULL DEFAULT true,
    deleted_at timestamptz
);
CREATE UNIQUE INDEX ux_notice_config_business_id ON notice_config (business_id);
CREATE INDEX ix_notice_config_user ON notice_config (user_id, created_at DESC) WHERE deleted_at IS NULL;
CREATE INDEX ix_notice_config_user_enabled ON notice_config (user_id, enabled) WHERE deleted_at IS NULL;

CREATE TABLE notice_deliveries (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id uuid NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
