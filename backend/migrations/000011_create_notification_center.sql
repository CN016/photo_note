    delivery_status varchar(16) NOT NULL DEFAULT 'pending',
    attempt_count smallint NOT NULL DEFAULT 0,
    next_attempt_at timestamptz NOT NULL DEFAULT now(),
    last_attempt_at timestamptz,
    delivered_at timestamptz,
    last_error_code varchar(64) NOT NULL DEFAULT ''
);
CREATE UNIQUE INDEX ux_notice_deliveries_business_id ON notice_deliveries (business_id);
CREATE INDEX ix_notice_deliveries_ready ON notice_deliveries (next_attempt_at, created_at)
    WHERE delivery_status IN ('pending', 'retry');
CREATE INDEX ix_notice_deliveries_user_created ON notice_deliveries (user_id, created_at DESC);
CREATE INDEX ix_notice_deliveries_notification ON notice_deliveries (user_id, notification_business_id);
CREATE INDEX ix_notice_deliveries_config ON notice_deliveries (user_id, notice_config_business_id);

