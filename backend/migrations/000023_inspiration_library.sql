COMMENT ON COLUMN inspiration_goals.orgid IS '空间业务编号，个人空间为 -1，组织空间为 organizations.orgid，禁止使用内部主键。';

COMMENT ON COLUMN inspiration_goals.created_at IS '创建时间，带时区。';

COMMENT ON COLUMN inspiration_goals.updated_at IS '最近更新时间，带时区。';

COMMENT ON COLUMN inspiration_goals.user_id IS '资源创建者用户业务 UUID，与 orgid 共同限制访问，不创建外键。';

COMMENT ON COLUMN inspiration_goals.enabled IS '是否启用每日目标和后台提醒。';

COMMENT ON COLUMN inspiration_goals.target IS '每日要求成功入库的图片数量，启用时服务层要求正整数。';

COMMENT ON COLUMN inspiration_goals.reminder_time IS '北京时间提醒时刻，格式 HH:mm。';

CREATE TABLE inspiration_activities (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id uuid NOT NULL UNIQUE,
  orgid bigint NOT NULL CHECK (orgid = -1 OR orgid BETWEEN 1 AND 9007199254740991),
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  user_id uuid NOT NULL,
  day date NOT NULL,
  saved_count integer NOT NULL DEFAULT 0 CHECK (saved_count >= 0),
  target integer CHECK (target > 0),
  reminder_notification_id uuid,
  reminder_acknowledged_at timestamptz
);

COMMENT ON TABLE inspiration_activities IS '灵感库成功存图的每日累计记录；删除图片不扣除次数。';

COMMENT ON COLUMN inspiration_activities.id IS '数据库内部自增主键，不作为接口标识或关联键。';

