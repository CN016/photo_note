COMMENT ON COLUMN inspiration_processing_jobs.user_id IS '资源创建者用户业务 UUID，与 orgid 共同限制访问，不创建外键。';

COMMENT ON COLUMN inspiration_processing_jobs.inspiration_id IS '所属灵感图业务 UUID；删除或代次变化后丢弃，不创建外键。';

COMMENT ON COLUMN inspiration_processing_jobs.image_key IS '已授权私有 storekey，仅服务端使用，不输出到错误日志。';

