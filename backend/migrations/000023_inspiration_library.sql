CREATE TABLE inspiration_goals (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id uuid NOT NULL UNIQUE,
  orgid bigint NOT NULL CHECK (orgid = -1 OR orgid BETWEEN 1 AND 9007199254740991),
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  user_id uuid NOT NULL,
  enabled boolean NOT NULL DEFAULT false,
  target integer NOT NULL DEFAULT 0 CHECK (target >= 0),
  reminder_time varchar(5) NOT NULL DEFAULT '20:00' CHECK (reminder_time ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$')
);

COMMENT ON TABLE inspiration_goals IS '灵感库每日存图目标；按空间及创建者隔离。';

COMMENT ON COLUMN inspiration_goals.id IS '数据库内部自增主键，不作为接口标识或关联键。';

