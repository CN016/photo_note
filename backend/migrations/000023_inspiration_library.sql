COMMENT ON COLUMN inspiration_activities.orgid IS '空间业务编号，个人空间为 -1，组织空间为 organizations.orgid，禁止使用内部主键。';

COMMENT ON COLUMN inspiration_activities.created_at IS '创建时间，带时区。';

COMMENT ON COLUMN inspiration_activities.updated_at IS '最近更新时间，带时区。';

COMMENT ON COLUMN inspiration_activities.user_id IS '资源创建者用户业务 UUID，与 orgid 共同限制访问，不创建外键。';

COMMENT ON COLUMN inspiration_activities.day IS '北京时间入库日期；不含时分秒。';

COMMENT ON COLUMN inspiration_activities.saved_count IS '当天成功创建的灵感图记录数量，不随编辑、重试或删除改变。';

COMMENT ON COLUMN inspiration_activities.target IS '当天目标数量快照，NULL 表示当天未启用目标，不追溯判为失败。';

COMMENT ON COLUMN inspiration_activities.reminder_notification_id IS '当天未达标通知的业务 UUID，用于原子确认弹窗；不创建外键。';

COMMENT ON COLUMN inspiration_activities.reminder_acknowledged_at IS '用户确认当天弹窗的时间，NULL 表示尚未确认。';

CREATE TABLE inspiration_processing_jobs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id uuid NOT NULL UNIQUE,
  orgid bigint NOT NULL CHECK (orgid = -1 OR orgid BETWEEN 1 AND 9007199254740991),
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  user_id uuid NOT NULL,
  inspiration_id uuid NOT NULL,
  image_key text NOT NULL,
  async_version bigint NOT NULL,
  algorithm text NOT NULL,
  stage text NOT NULL DEFAULT 'pending_compression' CHECK (stage IN ('pending_compression','compressing','pending_analysis','analyzing','succeeded','failed','unsupported','canceled')),
  attempts integer NOT NULL DEFAULT 0,
  next_attempt_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  lease_until timestamptz,
  lease_token uuid,
  error_code text NOT NULL DEFAULT ''
