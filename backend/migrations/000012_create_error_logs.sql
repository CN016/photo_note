COMMENT ON COLUMN error_logs.created_at IS '错误首次记录时间，使用带时区时间并统一以 UTC 保存。';
COMMENT ON COLUMN error_logs.updated_at IS '错误日志最后一次聚合更新时间，使用带时区时间并统一以 UTC 保存。';
COMMENT ON COLUMN error_logs.dedup_key IS '错误去重摘要，优先按源文件和代码行计算 SHA-256；无源码位置时使用错误码和原因类型区分。';
COMMENT ON COLUMN error_logs.http_status IS '错误对应的 HTTP 状态码；后台任务错误使用 500。';
COMMENT ON COLUMN error_logs.error_code IS '服务端稳定错误码或后台任务错误类型，不包含用户输入内容。';
COMMENT ON COLUMN error_logs.error_message IS '面向内部排查的稳定错误说明，不保存请求正文或认证凭据。';
