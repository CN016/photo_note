BEGIN;

CREATE TABLE error_logs (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id uuid NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    dedup_key char(64) NOT NULL,
    http_status integer NOT NULL DEFAULT 500,
    error_code varchar(64) NOT NULL,
    error_message text NOT NULL,
    cause_type varchar(128) NOT NULL DEFAULT '',
    cause_message text NOT NULL DEFAULT '',
    source_file text NOT NULL DEFAULT '',
    source_line integer NOT NULL DEFAULT 0,
    source_function text NOT NULL DEFAULT '',
    stack_trace text NOT NULL DEFAULT '',
    request_id uuid,
    http_method varchar(16) NOT NULL DEFAULT '',
    http_route text NOT NULL DEFAULT '',
    occurrence_count bigint NOT NULL DEFAULT 1,
    last_seen_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_error_logs_business_id ON error_logs (business_id);
CREATE INDEX ix_error_logs_dedup_last_seen ON error_logs (dedup_key, last_seen_at DESC);
CREATE INDEX ix_error_logs_created_at ON error_logs (created_at DESC);
CREATE INDEX ix_error_logs_code_created ON error_logs (error_code, created_at DESC);

